def parse_pattern(pattern):
    mask = 0
    golden = 0

    for char in pattern:
        if char == "_" or char == " ":
            continue

        mask <<= 1
        golden <<= 1

        if char == "0":
            mask |= 1
        elif char == "1":
            mask |= 1
            golden |= 1
        elif char != "?":
            raise ValueError("incorrect pattern: " + pattern)

    return mask, golden


def main():
    output = [
        "#ifndef DECODE_H",
        "#define DECODE_H",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by scripts/generate_inst_patterns.py.",
        "// Do not edit this file directly.",
        "",
    ]

    for name, pattern in INST_PATTERN:
        mask, golden = parse_pattern(pattern)

        output.append("// " + name + ": " + pattern)
        output.append(
            "#define {:<14} UINT32_C(0x{:08x})".format("MASK_" + name, mask)
        )
        output.append(
            "#define {:<14} UINT32_C(0x{:08x})".format(
                "GOLDEN_" + name, golden
            )
        )
        output.append("")

    output.append("#endif")
    output.append("")

    with open("include/decode.h", "w") as output_file:
        output_file.write("\n".join(output))

    print("Generated include/decode.h")


if __name__ == "__main__":
    main()
